CREATE TABLE establishment_calendar_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id BIGINT NOT NULL REFERENCES establishments(id),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    reason VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_establishment_calendar_blocks_period CHECK (starts_at < ends_at)
);
CREATE INDEX idx_establishment_calendar_blocks_range
    ON establishment_calendar_blocks (establishment_id, starts_at, ends_at);
